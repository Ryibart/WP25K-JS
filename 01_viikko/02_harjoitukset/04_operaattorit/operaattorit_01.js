/* 
- Luo muuttujat a ja b ja anna niille kokonaislukuarvot.
- Käytä yhteen-, vähennys-, kerto- ja jakolaskuoperaattoreita muuttujille a ja b. Tallenna jokainen tulos erilliseen muuttujaan (summa, erotus, tulo, osamäärä, jakojäännös).

- Käytä console.log() -metodia tulostamaan jokaisen operaation tulos konsoliin.

- Lisää kommentteja koodiin selittämään, mitä kukin operaatio tekee.
*/
let a = 10;
let b = 3;
// Yhteenlasku
let summa = a + b; // Laskee a:n ja b:n summan
console.log(`Summa: ${summa}`); // Tulostaa summan konsoliin
// Vähennyslasku
let erotus = a - b; // Laskee a:n ja b:n erotuksen
console.log(`Erotus: ${erotus}`); // Tulostaa erotuksen konsoliin
// Kertolasku
let tulo = a * b; // Laskee a:n ja b:n tulon
console.log(`Tulo: ${tulo}`); // Tulostaa tulon konsoliin
// Jakolasku
let osamaara = a / b; // Laskee a:n ja b:n jakolaskun tuloksen
console.log(`Osamäärä: ${osamaara}`); // Tulostaa osamäärän konsoliin
// Jakojäännös
let jakojaannos = a % b; // Laskee a:n ja b:n jakojäännöksen
console.log(`Jakojäännös: ${jakojaannos}`); // Tulostaa jakojäännöksen konsoliin